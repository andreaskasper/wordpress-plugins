/* Block "PrivacyPilot document" – no build step needed. */
(function (wp) {
	'use strict';
	if (!wp || !wp.blocks) {
		return;
	}
	var el = wp.element.createElement;
	var __ = wp.i18n.__;
	var docs = (window.goo1PpBlock && window.goo1PpBlock.documents) || [];
	var InspectorControls = (wp.blockEditor || wp.editor).InspectorControls;
	var useBlockProps = wp.blockEditor && wp.blockEditor.useBlockProps;

	wp.blocks.registerBlockType('goo1/privacypilot-document', {
		apiVersion: 2,
		title: 'PrivacyPilot',
		description: __('Privacy policy, cookie policy, terms or imprint generated by PrivacyPilot.', 'goo1-privacypilot'),
		icon: 'shield',
		category: 'widgets',
		attributes: {
			doc: { type: 'string', default: 'privacy' },
			lang: { type: 'string', default: 'auto' }
		},
		edit: function (props) {
			var a = props.attributes;
			var blockProps = useBlockProps ? useBlockProps() : {};
			return el('div', blockProps,
				el(InspectorControls, {},
					el(wp.components.PanelBody, { title: 'PrivacyPilot' },
						el(wp.components.SelectControl, {
							label: __('Document', 'goo1-privacypilot'),
							value: a.doc,
							options: docs,
							onChange: function (v) { props.setAttributes({ doc: v }); }
						}),
						el(wp.components.SelectControl, {
							label: __('Language', 'goo1-privacypilot'),
							value: a.lang,
							options: [{ value: 'auto', label: 'auto' }, { value: 'en', label: 'English' }, { value: 'de', label: 'Deutsch' }],
							onChange: function (v) { props.setAttributes({ lang: v }); }
						})
					)
				),
				el(wp.serverSideRender, { block: 'goo1/privacypilot-document', attributes: a })
			);
		},
		save: function () { return null; }
	});
})(window.wp);
